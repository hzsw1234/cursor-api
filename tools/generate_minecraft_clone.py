    W("    const dist = mp.distanceTo(pp);")
    W("    this.attackCd = Math.max(0, this.attackCd - dt);")
    W("    let dir = new THREE.Vector3();")
    W("    if (dist < 28) dir.subVectors(pp, mp).normalize();")
    W("    else {")
    W("      this.wanderT -= dt;")
    W("      if (this.wanderT <= 0) {")
