    W("          else if (rng.next() < 0.03) this.set(x, y + 1, z, 18);")
    W("          else if (rng.next() < 0.01 && here === 2) this.set(x, y + 1, z, 21);")
    W("        }")
    W("      }")
    W("    }")
    W("    for (let i = 0; i < STRUCTURE_OFFSETS.length; i++) {")
    W("      const so = STRUCTURE_OFFSETS[i];")
