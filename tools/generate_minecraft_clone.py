    W("  sampleGround(x, z) {")
    W("    let y = 90;")
    W("    while (y > 1 && !BLOCK_DEFS[this.world.getBlock(Math.floor(x), y, Math.floor(z))]?.solid) y--;")
    W("    return y + 1;")
    W("  }")
    W("  collides(x,y,z) {")
    W("    const w = 0.3;")
    W("    for (let dx = -1; dx <= 1; dx++) {")
    W("      for (let dy = 0; dy <= 2; dy++) {")
