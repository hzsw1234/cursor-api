    W("    const nx = mp.x + dir.x * step, nz = mp.z + dir.z * step;")
    W("    let ny = mp.y;")
    W("    const ground = this.sampleGround(nx, nz);")
    W("    ny = ground + 0.8;")
    W("    if (!this.collides(nx, ny, nz)) { mp.x = nx; mp.z = nz; mp.y = ny; }")
